/** Classification rules for item-attached labels. */

export function isHeightLabelText(inventoryName, text) {
  const value = String(text || '').trim();
  if (!value) return false;
  if (/^\d+(?:\s*[-–]\s*\d+)?\s*H$/i.test(value)) return true;
  return /upright space heater/i.test(String(inventoryName || '')) && /^\d+(?:\.\d+)?\s*(?:"|in(?:ches)?)$/i.test(value);
}

export function automaticLabelMeta(inventoryName, text) {
  return {
    autoGenerated: true,
    labelKind: isHeightLabelText(inventoryName, text) ? 'item-height' : 'item-detail',
  };
}

export function isOptionalHeightLabel(attrs = {}) {
  return !!(attrs.autoGenerated && attrs.labelKind === 'item-height');
}
